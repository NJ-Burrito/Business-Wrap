"""Compile a design pack (DTCG tokens) into the flat theme the renderer reads.

  python design/build.py                 # design/ours/pack.json -> design/ours/theme.json
  python design/build.py design/custom/<name>/pack.json
Runs the palette contrast gate first and refuses to write a theme that fails it.
The theme shape is the editor engine's: {name, fonts, sizes, page, space, rules, vars, logos, brand}.
"""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "palette"))
import check as palette  # noqa: E402


def print_value(tok):
    ext = tok.get("$extensions", {}).get("business-wrap", {})
    if "print" in ext:
        return ext["print"]
    v = tok["$value"]
    return f'{v["value"]}{v["unit"]}' if isinstance(v, dict) else v


def group(node):
    return {k: print_value(v) for k, v in node.items() if not k.startswith("$")}


def build(pack_path: Path) -> int:
    pack = json.loads(pack_path.read_text(encoding="utf-8"))
    base = pack_path.parent
    pal_path = (base / pack["tokens"]["palette"]).resolve()
    typ_path = (base / pack["tokens"]["typography"]).resolve()
    if palette.main([str(pal_path)]) != 0:
        print("design/build: palette gate FAILED, theme not written")
        return 1
    pal = json.loads(pal_path.read_text(encoding="utf-8"))
    typ = json.loads(typ_path.read_text(encoding="utf-8"))
    vars_ = {k: palette.role_hex(pal, k) for k in pal["color"]["role"] if not k.startswith("$")}
    for name, steps in pal["color"]["ramp"].items():
        for step, t in steps.items():
            if not step.startswith("$"):
                vars_[f"{name}-{step}"] = palette.hex_of(t["$value"])
    for k, t in pal["color"]["diagram"].items():
        if not k.startswith("$"):
            vars_[f"diagram-{k}"] = palette.hex_of(t["$value"])
    fam = typ["font"]["family"]
    banned = [b.lower() for b in pack.get("bannedFonts", [])]
    for role in ("text", "display"):
        for f in fam[role]["$value"]:
            if any(b in f.lower() for b in banned):
                print(f"design/build: banned font {f!r} in role {role}")
                return 1
    theme = {
        "$comment": f"GENERATED by design/build.py from {pack_path.relative_to(ROOT).as_posix()} — edit the tokens, not this file.",
        "name": pack["name"],
        "fonts": {"text": fam["text"]["$value"][0], "display": fam["display"]["$value"][0]},
        "weights": {k: v["$value"] for k, v in typ["font"]["weight"].items() if not k.startswith("$")},
        "sizes": group(typ["font"]["size"]),
        "lineHeights": {k: v["$value"] for k, v in typ["font"]["lineHeight"].items() if not k.startswith("$")},
        "space": group(typ["space"]),
        "rules": group(typ["rule"]),
        "page": group(typ["page"]),
        "brand": {"producer": "", "confidential": ""},
        "vars": vars_,
        "logos": {"start": "", "center": "", "end": "", "header": ""},
    }
    out = base / "theme.json"
    out.write_text(json.dumps(theme, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    print(f"design/build: wrote {out.relative_to(ROOT).as_posix()} ({len(vars_)} colour vars)")
    return 0


if __name__ == "__main__":
    arg = sys.argv[1] if len(sys.argv) > 1 else ROOT / "design" / "ours" / "pack.json"
    sys.exit(build(Path(arg).resolve()))
