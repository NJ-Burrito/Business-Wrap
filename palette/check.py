"""Palette gate: resolve DTCG aliases, check every contrast pair, write swatches.html.

Usage:
  python palette/check.py [tokens.json]            # gate + swatches.html beside the tokens
  python palette/check.py [tokens.json] --css      # also print CSS custom properties (--c-<role>)
Exit 1 if any pair is below its level or an alias does not resolve.
"""
import html
import json
import sys
from pathlib import Path


def load(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def lookup(root, dotted):
    node = root
    for part in dotted.split("."):
        node = node[part]
    return node


def resolve(root, value, seen=()):
    if isinstance(value, str) and value.startswith("{") and value.endswith("}"):
        ref = value[1:-1]
        if ref in seen:
            raise ValueError(f"alias cycle at {ref}")
        return resolve(root, lookup(root, ref)["$value"], seen + (ref,))
    return value


def hex_of(c):
    return c["hex"] if "hex" in c else "#%02x%02x%02x" % tuple(round(x * 255) for x in c["components"])


def luminance(h):
    h = h.lstrip("#")
    def lin(c):
        c /= 255
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = (lin(int(h[i:i + 2], 16)) for i in (0, 2, 4))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(a, b):
    la, lb = sorted((luminance(a), luminance(b)), reverse=True)
    return round((la + 0.05) / (lb + 0.05), 2)


def role_hex(root, name):
    if name == "white":
        return hex_of(root["color"]["white"]["$value"])
    group = root["color"]["role"] if name in root["color"]["role"] else root["color"]["component"]
    return hex_of(resolve(root, group[name]["$value"]))


def main(argv):
    if '--help' in argv or '-h' in argv:
        print(__doc__)
        return 0
    path = Path(next((a for a in argv if not a.startswith("--")), Path(__file__).with_name("tokens.json")))
    root = load(path)
    roles = {k: role_hex(root, k) for k in root["color"]["role"] if not k.startswith("$")}
    fails = []
    rows = []
    for label, fg, bg, need in root["$extensions"]["business-wrap"]["contrastPairs"]:
        c = contrast(role_hex(root, fg), role_hex(root, bg))
        ok = c >= need
        rows.append((label, fg, bg, c, need, ok))
        if not ok:
            fails.append(label)
        print(f"{'PASS' if ok else 'FAIL'} {label:<34} {c:>5}:1 (needs {need})")
    if "--css" in argv:
        print(":root{" + ";".join(f"--c-{k}:{v}" for k, v in roles.items()) + "}")
    sw = []
    for group, steps in root["color"]["ramp"].items():
        cells = "".join(
            f'<div class="sw" style="background:{hex_of(t["$value"])}"><b>{group} {k}</b><code>{hex_of(t["$value"])}</code></div>'
            for k, t in steps.items() if not k.startswith("$"))
        sw.append(f"<h3>{html.escape(group)}</h3><div class=row>{cells}</div>")
    role_cells = "".join(
        f'<div class="sw" style="background:{v}"><b>{k}</b><code>{v}</code><small>{html.escape(root["color"]["role"][k].get("$description", ""))}</small></div>'
        for k, v in roles.items())
    comps = {k: v for k, v in root["color"].get("component", {}).items() if not k.startswith("$")}
    comp_cells = "".join(
        f'<div class="sw" style="background:{role_hex(root, k)}"><b>{k}</b><code>{role_hex(root, k)}</code><small>{html.escape(v.get("$description", ""))}</small></div>'
        for k, v in comps.items())
    pair_rows = "".join(
        f"<tr><td>{'✔ PASS' if ok else '✖ FAIL'}</td><td>{html.escape(l)}</td><td>{fg} / {bg}</td><td>{c}:1</td><td>{n}:1</td></tr>"
        for l, fg, bg, c, n, ok in rows)
    out = path.with_name("swatches.html")
    out.write_text(f"""<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Palette swatches</title><style>
body{{font-family:system-ui,sans-serif;margin:16px;background:#fafaf9;color:#1b1813}}
.row{{display:flex;flex-wrap:wrap;gap:8px}}.sw{{width:150px;min-height:80px;padding:8px;border-radius:6px;border:1px solid #0002;display:flex;flex-direction:column;gap:2px}}
.sw b,.sw code,.sw small{{background:#fffd;padding:1px 4px;border-radius:3px;width:fit-content}}table{{border-collapse:collapse}}td{{padding:4px 8px;border-bottom:1px solid #ddd}}
</style></head><body>
<h1>Palette swatches <span dir="rtl" lang="ar">/ عينات الألوان</span></h1>
<p>Generated by <code>palette/check.py</code> from <code>{path.name}</code>. {'All contrast pairs pass.' if not fails else str(len(fails)) + ' pair(s) FAIL.'}
<span dir="rtl" lang="ar">{'جميع أزواج التباين ناجحة.' if not fails else 'يوجد زوج تباين راسب.'}</span></p>
<h2>Roles <span dir="rtl" lang="ar">/ الأدوار</span></h2><div class=row>{role_cells}</div>
<h2>On the page <span dir="rtl" lang="ar">/ على الصفحة</span></h2><div class=row>{comp_cells}</div>
<h2>Contrast <span dir="rtl" lang="ar">/ التباين</span></h2><table>{pair_rows}</table>
<h2>Ramps <span dir="rtl" lang="ar">/ التدرجات</span></h2>{''.join(sw)}
</body></html>""", encoding="utf-8")
    print(f"{'all pairs pass' if not fails else str(len(fails)) + ' FAIL'}; wrote {out.name}")
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
