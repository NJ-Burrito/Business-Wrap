HF = "0.8.144"


def tokens() -> dict[str, str]:
    css = (V3 / "tokens-v3.css").read_text(encoding="utf-8")
    block = css[css.index(":root {"):css.index("}", css.index(":root {"))]
    return dict(re.findall(r"--bw-([a-z0-9-]+):\s*([^;]+);", block))


T = tokens()
# Ramp steps used on the navy pieces that have no light-role name (all are dark-role values in tokens-v3.css).
RAMP = {"primary-900": "#002d5c", "primary-800": "#003c7a", "accent-500": "#be9a41", "neutral-50": "#fafaf9"}
for k, v in RAMP.items():
    assert v in T.values(), (k, v)


def mark(name: str, size: int) -> str:
    svg = (V3 / "logo" / name).read_text(encoding="utf-8")
    svg = re.sub(r"<title>.*?</title>", "", svg)
    svg = re.sub(r'\s(width|height)="64"', "", svg, count=2)
    svg = svg.replace("<svg ", f'<svg id="mark" width="{size}" height="{size}" ', 1)
    # stroke-dash draw for the two ink lines (pathLength 1 keeps the offsets in units)
    svg = re.sub(r'(<path class="ln [^"]+")', r'\1 pathLength="1"', svg)
    return svg


def font_face(fam: str, file: str, weight: int) -> str:
    return (f'@font-face{{font-family:"{fam}";src:url("./assets/fonts/{file}") format("woff2");'
            f"font-weight:{weight};font-display:block}}")


FACES = {
    "display": ("Thmanyah Serif Display", "thmanyahserifdisplay", "thmanyahserifdisplay-Bold.woff2", 700),
    "sans5": ("Thmanyah Sans", "thmanyahsans", "thmanyahsans-Medium.woff2", 500),
    "sans7": ("Thmanyah Sans", "thmanyahsans", "thmanyahsans-Bold.woff2", 700),
}


def project(slug: str, comp_id: str, w: int, h: int, dur: float, title: str, css: str, body: str, js: str,
            faces: list[str], lang: str = "en", words: list[str] | None = None) -> None:
    p = MOTION / slug
    (p / "assets" / "fonts").mkdir(parents=True, exist_ok=True)
    ff = []
    for f in faces:
        fam, d, file, wt = FACES[f]
        shutil.copy(FONTS / d / "woff2" / file, p / "assets" / "fonts" / file)
        ff.append(font_face(fam, file, wt))
    used = sorted(set(re.findall(r"var\(--bw-([a-z0-9-]+)\)", css + body)))
    root = ";".join(f"--bw-{k}:{T[k]}" for k in used if k in T)
    html = f"""<!doctype html>
<html lang="{lang}">
<head>
<meta charset="UTF-8" />
<meta name="viewport" content="width={w}, height={h}" />
<title>{title}</title>
<script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>
<style>
{chr(10).join(ff)}
/* Business-Wrap v3 tokens used here (values from brand/v3/tokens-v3.css; generated by build_media.py) */
:root{{{root}}}
*{{margin:0;padding:0;box-sizing:border-box}}
html,body{{width:{w}px;height:{h}px;overflow:hidden}}
{css}
</style>
</head>
<body>
<div id="stage" data-composition-id="{comp_id}" data-start="0" data-duration="{dur}" data-fps="25" data-width="{w}" data-height="{h}">
{body}
</div>
<script>
(() => {{
  const ID = "{comp_id}", D = {dur};
  const tl = gsap.timeline({{ paused: true }});
{js}
  tl.set({{}}, {{}}, D);
  window.__timelines = window.__timelines || {{}};
  window.__timelines[ID] = tl;
}})();
</script>
</body>
</html>
"""
    for k in re.findall(r"var\(--bw-([a-z0-9-]+)\)", html):
        assert k in T, f"{slug}: --bw-{k} not in tokens"
    (p / "index.html").write_text(html, encoding="utf-8", newline="\n")
    (p / "hyperframes.json").write_text(json.dumps({
        "$schema": "https://hyperframes.heygen.com/schema/hyperframes.json",
        "paths": {"blocks": "compositions", "components": "compositions/components", "assets": "assets"},
        "authoringSkill": "motion-graphics"}) + "\n", encoding="utf-8", newline="\n")
    (p / "meta.json").write_text(json.dumps({"id": comp_id, "name": comp_id,
                                             "createdAt": "2026-10-28T00:00:00.000Z"}) + "\n",
                                 encoding="utf-8", newline="\n")
    (p / "package.json").write_text(json.dumps({
        "name": comp_id, "private": True, "type": "module",
        "scripts": {"check": f"npx --yes hyperframes@{HF} check", "render": f"npx --yes hyperframes@{HF} render"}},
        indent=2) + "\n", encoding="utf-8", newline="\n")
    (p / "words.json").write_text(json.dumps(words or [], ensure_ascii=False, indent=2) + "\n",
                                  encoding="utf-8", newline="\n")
    print("ok", p / "index.html")


