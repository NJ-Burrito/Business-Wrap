"""Business-Wrap brand v3 media: writes the four HyperFrames projects (hero, hero-ar, github-banner, logo-loop)
from the v3 tokens and the v3 mark, so the media never drift from the brand files.

    python brand/v3/motion/build_media.py

Colours come only from brand/v3/tokens-v3.css (light block for the paper pieces, the band ramp for the navy pieces).
The mark is inlined from brand/v3/logo/mark-dark.svg (navy pieces) and mark.svg (paper pieces); the wordmark is
real Thmanyah Serif Display text. Fonts are copied from fonts/nj-fonts (git-ignored copies).
Storyboards: DESIGN j.1 (hero), j.2 (banner); motion tokens e.1 at 25 fps (e.6).
"""
from __future__ import annotations

