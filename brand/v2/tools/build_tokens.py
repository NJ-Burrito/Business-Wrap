"""Business-Wrap brand v2: tokens.json -> tokens.css + contrast.md.

    python brand/v2/tools/build_tokens.py          # writes both, exits 1 if any required pair fails
Exit 0 = every contrast pair meets its minimum in light AND dark.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

V2 = Path(__file__).resolve().parent.parent
T = json.loads((V2 / "tokens.json").read_text(encoding="utf-8"))


def lum(hex_: str) -> float:
    h = hex_.lstrip("#")
    out = []
    for i in (0, 2, 4):
        c = int(h[i:i + 2], 16) / 255
        out.append(c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4)
    r, g, b = out
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def ratio(a: str, b: str) -> float:
    la, lb = sorted((lum(a), lum(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def css() -> str:
    L, D = T["color"]["light"], T["color"]["dark"]
    lines = ["/* Business-Wrap brand v2 tokens (Ledger & Highlighter). Generated by tools/build_tokens.py from tokens.json: do not edit by hand. */",
             "/* Theme: light by default; dark follows the system unless [data-theme] says otherwise. Prefix: --bw- */", ":root {"]
    lines.append("  color-scheme: light dark;")
    for k, v in L.items():
        lines.append(f"  --bw-{k}: {v};")
    for k, v in T["font"].items():
        lines.append(f"  --bw-font-{k}: {v};")
    for k, v in T["weight"].items():
        lines.append(f"  --bw-weight-{k}: {v};")
    for k, v in T["size"].items():
        if not k.startswith("$"):
            lines.append(f"  --bw-size-{k}: {v};")
    for k, v in T["leading"].items():
        lines.append(f"  --bw-leading-{k}: {v};")
    for k, v in T["tracking"].items():
        lines.append(f"  --bw-tracking-{k}: {v};")
    for k, v in T["space"].items():
        lines.append(f"  --bw-space-{k}: {v};")
    for k, v in T["radius"].items():
        lines.append(f"  --bw-radius-{k}: {v};")
    for k, v in T["shadow"]["light"].items():
        lines.append(f"  --bw-shadow-{k}: {v};")
    for k, v in T["motion"]["duration"].items():
        lines.append(f"  --bw-dur-{k}: {v};")
    for k, v in T["motion"]["ease"].items():
        lines.append(f"  --bw-ease-{k}: {v};")
    lines.append("}")

    def dark_block(sel: str) -> list[str]:
        b = [f"{sel} {{"]
        b += [f"  --bw-{k}: {v};" for k, v in D.items()]
        b += [f"  --bw-shadow-{k}: {v};" for k, v in T["shadow"]["dark"].items()]
        b.append("}")
        return b

    lines.append("@media (prefers-color-scheme: dark) {")
    lines += ["  " + x for x in dark_block(':root:not([data-theme="light"])')]
    lines.append("}")
    lines += dark_block(':root[data-theme="dark"]')
    lines += ['@media (prefers-reduced-motion: reduce) {', "  :root {"]
    lines += [f"    --bw-dur-{k}: 1ms;" for k in T["motion"]["duration"]]
    lines += ["  }", "}"]
    lines += [
        "/* Base helpers any consumer may use. */",
        ".bw-highlight { background: linear-gradient(transparent 12%, var(--bw-accent) 12%, var(--bw-accent) 88%, transparent 88%); color: var(--bw-on-accent); padding-inline: .15em; border-radius: 2px; -webkit-box-decoration-break: clone; box-decoration-break: clone; }",
        ":where(a, button, input, select, textarea, [tabindex]):focus-visible { outline: 3px solid var(--bw-focus); outline-offset: 2px; }",
    ]
    return "\n".join(lines) + "\n"


def contrast() -> tuple[str, int]:
    fails = 0
    rows = ["# Contrast check (WCAG 2.2) — generated by tools/build_tokens.py", "",
            "| Foreground | Background | Use | Min | Light | Dark |", "|---|---|---|---|---|---|"]
    for fg, bg, mn, use in T["contrastPairs"]:
        cells = []
        for mode in ("light", "dark"):
            c = T["color"][mode]
            r = ratio(c[fg], c[bg])
            ok = r >= mn
            fails += 0 if ok else 1
            cells.append(f"{r:.2f} {'pass' if ok else 'FAIL'}")
        rows.append(f"| `{fg}` | `{bg}` | {use} | {mn} | {cells[0]} | {cells[1]} |")
    rows += ["", "The highlighter `accent` is a fill behind `on-accent` ink, never text or a thin line on a light ground "
             f"(accent on light bg = {ratio(T['color']['light']['accent'], T['color']['light']['bg']):.2f}:1); on light grounds a graphic accent uses `accent-strong`."]
    rows.append(f"\nResult: {'all pairs pass' if not fails else f'{fails} FAIL'}.")
    return "\n".join(rows) + "\n", fails


if __name__ == "__main__":
    (V2 / "tokens.css").write_text(css(), encoding="utf-8", newline="\n")
    md, fails = contrast()
    (V2 / "contrast.md").write_text(md, encoding="utf-8", newline="\n")
    print(md)
    sys.exit(1 if fails else 0)
