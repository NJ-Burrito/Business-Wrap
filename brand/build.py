"""Build the Business-Wrap identity: mark, lockups (EN, AR), light/dark, animated mark, PNG sizes, preview.

  uv run --with uharfbuzz --with fonttools --with resvg-py --with pillow python brand/build.py

Wordmarks are set in Thmanyah Serif Display Bold and converted to outlines (shaped by HarfBuzz, so
the Arabic joins correctly); the font file is read from BW_FONT_DIR (or .local/config.json fontDir)
and never copied. Colours come from palette/tokens.json. PNGs carry no metadata chunks.
"""
import io
import json
import os
from pathlib import Path

import resvg_py
import uharfbuzz as hb
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "brand"


def palette():
    t = json.loads((ROOT / "palette/tokens.json").read_text(encoding="utf-8"))
    ramp = lambda r, s: t["color"]["ramp"][r][s]["$value"]["hex"]
    return {
        "light": {"ink": ramp("primary", "800"), "accent": ramp("accent", "600"), "ground": ramp("neutral", "50")},
        "dark": {"ink": ramp("neutral", "50"), "accent": ramp("accent", "500"), "ground": ramp("primary", "950")},
    }


def font_path():
    root = os.environ.get("BW_FONT_DIR")
    if not root:
        try:
            root = json.loads((ROOT / ".local/config.json").read_text(encoding="utf-8"))["fontDir"]
        except (OSError, KeyError, ValueError):
            raise SystemExit("set BW_FONT_DIR (font root) or .local/config.json fontDir")
    p = Path(root) / "thmanyahserifdisplay" / "ttf" / "thmanyahserifdisplay-Bold.ttf"
    if not p.exists():
        raise SystemExit(f"missing {p.name} under the font root (convert to ttf first, fonts/README.md)")
    return p


# --- the mark: a page drawn as one open stroke (the wrap) whose seam is the folded corner (accent) ---
WRAP = "M35 8H22A7 7 0 0 0 15 15V49A7 7 0 0 0 22 56H42A7 7 0 0 0 49 49V22"
FOLD = "M35 8V18A4 4 0 0 0 39 22H49"
LINE = "M24 32H40M24 43H32"
LEN = {"wrap": 128, "fold": 27, "line": 25}  # dash lengths >= path lengths (127.0, 26.3, 16+8)


def mark_group(c, cls=False):
    k = (lambda n: f' class="{n}"') if cls else (lambda n: "")
    return (f'<g fill="none" stroke-width="7" stroke-linecap="round" stroke-linejoin="round">'
            f'<path{k("wrap")} stroke="{c["ink"]}" d="{WRAP}"/>'
            f'<path{k("line")} stroke="{c["ink"]}" d="{LINE}"/>'
            f'<path{k("fold")} stroke="{c["accent"]}" d="{FOLD}"/></g>')


HEAD = "<!-- Business-Wrap identity. Tool brand only: never placed in document outputs. Generated by brand/build.py. -->\n"


def mark_svg(c, size=64):
    return (HEAD + f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="{size}" height="{size}" '
            f'role="img" aria-label="Business-Wrap">{mark_group(c)}</svg>\n')


def favicon_svg(pal):
    l, d = pal["light"], pal["dark"]
    return (HEAD + '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="64" height="64" role="img" aria-label="Business-Wrap">'
            f'<style>.i{{stroke:{l["ink"]}}}.a{{stroke:{l["accent"]}}}@media (prefers-color-scheme:dark){{.i{{stroke:{d["ink"]}}}.a{{stroke:{d["accent"]}}}}}</style>'
            f'<g fill="none" stroke-width="7" stroke-linecap="round" stroke-linejoin="round">'
            f'<path class="i" d="{WRAP}"/><path class="i" d="{LINE}"/><path class="a" d="{FOLD}"/></g></svg>\n')


def animated_svg(pal):
    l, d = pal["light"], pal["dark"]
    ease = "cubic-bezier(.2,.8,.2,1)"
    css = f"""
.wrap,.line{{stroke:var(--bw-ink,{l["ink"]})}}.fold{{stroke:var(--bw-accent,{l["accent"]})}}
@media (prefers-color-scheme:dark){{.wrap,.line{{stroke:var(--bw-ink,{d["ink"]})}}.fold{{stroke:var(--bw-accent,{d["accent"]})}}}}
.wrap{{stroke-dasharray:{LEN["wrap"]};stroke-dashoffset:0}}
.line{{stroke-dasharray:{LEN["line"]};stroke-dashoffset:0}}
.fold{{stroke-dasharray:{LEN["fold"]};stroke-dashoffset:0;transform-box:view-box;transform-origin:49px 8px;transition:transform 220ms {ease}}}
/* reveal (once): the wrap draws, the corner folds over out of the seam, the line is written. ~900 ms. */
@keyframes bw-wrap{{from{{stroke-dashoffset:{LEN["wrap"]}}}to{{stroke-dashoffset:0}}}}
@keyframes bw-fold{{0%{{stroke-dashoffset:{LEN["fold"]};transform:rotate(-24deg)}}70%{{stroke-dashoffset:0;transform:rotate(4deg)}}100%{{stroke-dashoffset:0;transform:rotate(0)}}}}
@keyframes bw-line{{from{{stroke-dashoffset:{LEN["line"]}}}to{{stroke-dashoffset:0}}}}
#reveal:target ~ .mark .wrap,.bw-reveal .wrap,svg:not(.bw-still) .mark .wrap{{animation:bw-wrap 520ms {ease} both}}
#reveal:target ~ .mark .fold,.bw-reveal .fold,svg:not(.bw-still) .mark .fold{{animation:bw-fold 300ms {ease} 460ms both}}
#reveal:target ~ .mark .line,.bw-reveal .line,svg:not(.bw-still) .mark .line{{animation:bw-line 200ms {ease} 700ms both}}
/* hover / focus micro-motion: the corner lifts a little, like a page about to turn. */
svg:hover .fold,.bw-hover .fold,:focus-visible > svg .fold{{transform:rotate(-9deg)}}
@media (prefers-reduced-motion:reduce){{.wrap,.fold,.line{{animation:none!important;stroke-dashoffset:0!important;transform:none!important;transition:none!important}}}}
"""
    group = mark_group({"ink": "", "accent": ""}, cls=True).replace(' stroke=""', "")
    return (HEAD + '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="64" height="64" role="img" aria-label="Business-Wrap">'
            f'<style>{css}</style><g id="reveal"/><g class="mark">{group}</g></svg>\n')


def text_path(text, font_file, size, rtl=False):
    """Shape with HarfBuzz, draw outlines with fontTools. Returns (path d, advance width, ascent) in px."""
    blob = hb.Blob.from_file_path(str(font_file))
    face = hb.Face(blob)
    f = hb.Font(face)
    buf = hb.Buffer()
    buf.add_str(text)
    buf.guess_segment_properties()
    hb.shape(f, buf, {"kern": True, "liga": True})
    tt = TTFont(str(font_file))
    gs = tt.getGlyphSet()
    order = tt.getGlyphOrder()
    upem = tt["head"].unitsPerEm
    s = size / upem
    pen = SVGPathPen(gs)
    x = 0
    for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
        name = order[info.codepoint]
        tp = TransformPen(pen, (s, 0, 0, -s, (x + pos.x_offset) * s, -pos.y_offset * s))
        gs[name].draw(tp)
        x += pos.x_advance
    return pen.getCommands(), x * s, tt["hhea"].ascent * s


def lockup_svg(c, word, font_file, rtl):
    h, gap, size = 64, 18, 34
    d, w, _ = text_path(word, font_file, size, rtl)
    base = 44  # baseline aligned to the page's optical centre
    width = round(64 + gap + w + 4)
    if rtl:
        mark = f'<g transform="translate({width - 64} 0)">{mark_group(c)}</g>'
        txt = f'<path fill="{c["ink"]}" transform="translate(2 {base})" d="{d}"/>'
    else:
        mark = mark_group(c)
        txt = f'<path fill="{c["ink"]}" transform="translate({64 + gap} {base})" d="{d}"/>'
    return (HEAD + f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {h}" width="{width}" height="{h}" '
            f'role="img" aria-label="{word}">{mark}{txt}</svg>\n'), width


def png(svg, size, ground=None, radius=0.22):
    raw = resvg_py.svg_to_bytes(svg_string=svg, width=size, height=size)
    im = Image.open(io.BytesIO(bytes(raw))).convert("RGBA")
    if ground:
        tile = Image.new("RGBA", (size, size), (0, 0, 0, 0))
        from PIL import ImageDraw
        g = tuple(int(ground[i:i + 2], 16) for i in (1, 3, 5)) + (255,)
        ImageDraw.Draw(tile).rounded_rectangle([0, 0, size - 1, size - 1], radius=round(size * radius), fill=g)
        inner = im.resize((round(size * 0.78),) * 2, Image.LANCZOS)
        off = (size - inner.size[0]) // 2
        tile.alpha_composite(inner, (off, off))
        im = tile
    b = io.BytesIO()
    im.save(b, "PNG", optimize=True)  # no pnginfo: no tEXt/iTXt/eXIf chunks
    return b.getvalue()


def main():
    pal = palette()
    ff = font_path()
    (OUT / "logo").mkdir(parents=True, exist_ok=True)
    (OUT / "png").mkdir(exist_ok=True)
    w = lambda p, s: (OUT / p).write_text(s, encoding="utf-8", newline="\n")
    w("logo/mark.svg", mark_svg(pal["light"]))
    w("logo/mark-dark.svg", mark_svg(pal["dark"]))
    w("logo/mark-animated.svg", animated_svg(pal))
    w("logo/favicon.svg", favicon_svg(pal))
    lock = {}
    for lang, word, rtl in (("en", "Business Wrap", False), ("ar", "بزنس راب", True)):
        for mode in ("light", "dark"):
            svg, width = lockup_svg(pal[mode], word, ff, rtl)
            w(f"logo/lockup-{lang}{'' if mode == 'light' else '-dark'}.svg", svg)
            lock[(lang, mode)] = (svg, width)
    for n in (16, 32, 48, 64, 128, 180, 192, 256, 512):
        (OUT / f"png/mark-{n}.png").write_bytes(png(mark_svg(pal["light"]), n, pal["light"]["ground"]))
        (OUT / f"png/mark-dark-{n}.png").write_bytes(png(mark_svg(pal["dark"]), n, pal["dark"]["ground"]))
    # preview board: light and dark rows, mark + EN + AR lockups
    W, H = 1400, 620
    board = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    for row, mode in enumerate(("light", "dark")):
        g = tuple(int(pal[mode]["ground"][i:i + 2], 16) for i in (1, 3, 5)) + (255,)
        board.paste(Image.new("RGBA", (W, H // 2), g), (0, row * H // 2))
        y = row * H // 2 + 70
        m = Image.open(io.BytesIO(bytes(resvg_py.svg_to_bytes(svg_string=mark_svg(pal[mode]), width=170, height=170))))
        board.alpha_composite(m.convert("RGBA"), (60, y))
        x = 290
        for lang in ("en", "ar"):
            svg, width = lock[(lang, mode)]
            hgt = 110
            im = Image.open(io.BytesIO(bytes(resvg_py.svg_to_bytes(svg_string=svg, width=round(width * hgt / 64), height=hgt)))).convert("RGBA")
            board.alpha_composite(im, (x, y + 30))
            x += im.size[0] + 70
    b = io.BytesIO()
    board.convert("RGB").save(b, "PNG", optimize=True)
    (OUT / "preview.png").write_bytes(b.getvalue())
    print("brand: mark, animated, favicon, 4 lockups, 18 PNGs, preview.png")


if __name__ == "__main__":
    main()
